#!/usr/bin/env python3
"""Generate the RetroAchievements memory map of the 3DS build.

RetroAchievements addresses GBA memory as IWRAM at 0x00000-0x07FFF (GBA
0x03000000) followed by EWRAM at 0x08000-0x47FFF (GBA 0x02000000). The
original game keeps its globals at fixed addresses there, and the
decompilation's linker.ld lists every one of them. In this port those
globals are ordinary C variables the linker places anywhere; gEwram/gIwram
only hold what the code addresses through them (the BG buffers). So an RA
address means something only through this table: GBA offset -> the native
variable that holds those bytes.

The 3DS build is 32-bit ARM like the GBA, so the structs keep the original
layout; a variable is mapped over min(its native size, the distance to the
next mapped variable). A linker.ld name the port does not define is left out
(reads fall back to gEwram/gIwram); a few live under another name (ALIASES).

Usage:  python3 tools/gen_ra_map.py <tmc-3ds.elf> [--nm PATH]
        writes platform/3ds/source/retro_ach_map_3ds.c

Run it again when linker.ld changes or a mapped variable is renamed: the
build then fails to link instead of reading the wrong memory.
"""
import argparse
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "platform", "3ds", "source", "retro_ach_map_3ds.c")

# linker.ld name -> the port's variable, where the port keeps it elsewhere.
ALIASES = {
    "gMenu": "_gMenuSharedStorage",
    "gIntroState": "_gMenuSharedStorage",
    "gChooseFileState": "_gMenuSharedStorage",
}
# Never mapped: functions copied to IWRAM, stacks, end markers.
SKIP = re.compile(r"^(ram_|usr_stack|irq_stack|gEndOfEwram$|soft_reset_flag$)")


def linker_symbols(path):
    """(region, offset, name) of the retail (non-demo) layout."""
    out, region, skipping = [], None, False
    for line in open(path):
        s = line.strip()
        if s.startswith("ewram (NOLOAD)"):
            region = "E"
        elif s.startswith("iwram (NOLOAD)"):
            region = "I"
        elif s.startswith("rom :"):
            region = None
        if s.startswith("#if"):
            # The demo builds have their own tail; the EU/USA split is only
            # functions (skipped anyway).
            skipping = "DEMO" in s and "EU" not in s
            continue
        if s.startswith("#else"):
            skipping = not skipping
            continue
        if s.startswith("#endif"):
            skipping = False
            continue
        m = re.match(r"\. = 0x([0-9A-Fa-f]+); (\w+) = \.;", s)
        if m and region and not skipping and not SKIP.match(m.group(2)):
            out.append((region, int(m.group(1), 16), m.group(2)))
    return out


def native_symbols(nm, elf):
    syms = {}
    for line in subprocess.run([nm, "-S", "--defined-only", elf], capture_output=True, text=True,
                               check=True).stdout.splitlines():
        p = line.split()
        if len(p) == 4 and p[2] in ("B", "D"):
            syms[p[3]] = int(p[1], 16)
    return syms


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("elf")
    base = os.path.join(os.environ.get("DEVKITARM", "/opt/devkitpro/devkitARM"), "bin", "arm-none-eabi-")
    ap.add_argument("--nm", default=base + "nm")
    args = ap.parse_args()

    native = native_symbols(args.nm, args.elf)
    entries = {}  # RA address -> (name, native name, native size)
    missing = []
    for region, off, name in linker_symbols(os.path.join(ROOT, "linker.ld")):
        target = ALIASES.get(name, name)
        address = off if region == "I" else 0x8000 + off
        if target not in native:
            missing.append(name)
            continue
        entries.setdefault(address, (name, target, native[target]))

    rows = []
    addresses = sorted(entries)
    for i, address in enumerate(addresses):
        name, target, size = entries[address]
        limit = 0x8000 if address < 0x8000 else 0x48000
        nxt = addresses[i + 1] if i + 1 < len(addresses) else limit
        length = min(size, nxt - address, limit - address)
        if length > 0:
            rows.append((address, length, name, target))

    with open(OUT, "w") as f:
        f.write("/* Generated by tools/gen_ra_map.py from linker.ld and the linked ELF: do not edit.\n"
                " * RetroAchievements address (IWRAM 0x00000, EWRAM 0x08000) -> the port's variable. */\n")
        f.write('#include "retro_ach_map_3ds.h"\n\n')
        for target in sorted({r[3] for r in rows}):
            f.write("extern unsigned char %s[];\n" % target)
        f.write("\nconst RaMapEntry gRaMap[] = {\n")
        for address, length, name, target in rows:
            note = "" if name == target else "  /* %s */" % name
            f.write("    { 0x%05X, 0x%04X, %s },%s\n" % (address, length, target, note))
        f.write("};\nconst unsigned gRaMapCount = sizeof(gRaMap) / sizeof(gRaMap[0]);\n")
    print("%d variables mapped, %d linker.ld names not in this build: %s" %
          (len(rows), len(missing), " ".join(missing)), file=sys.stderr)


if __name__ == "__main__":
    main()
